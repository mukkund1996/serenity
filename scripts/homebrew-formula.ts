/**
 * Writes the Homebrew formula for a release (ADR 0014, 0025). The release
 * workflow commits its output to mukkund1996/homebrew-tap as Formula/serenity.rb.
 * Usage: bun scripts/homebrew-formula.ts <version> <SHA256SUMS file>
 */
import { readFileSync } from "node:fs";

const [rawVersion, sumsPath] = process.argv.slice(2);
if (!rawVersion || !sumsPath) {
	console.error(
		"usage: bun scripts/homebrew-formula.ts <version> <SHA256SUMS file>",
	);
	process.exit(2);
}
const version = rawVersion.replace(/^v/, "");

const sums = new Map<string, string>();
for (const line of readFileSync(sumsPath, "utf8").split("\n")) {
	const [sha, file] = line.trim().split(/\s+/);
	if (sha && file) sums.set(file, sha);
}

const base = `https://github.com/mukkund1996/serenity/releases/download/v${version}`;
const asset = (target: string) => {
	const file = `serenity-${target}`;
	const sha = sums.get(file);
	if (!sha) throw new Error(`${file} is not in ${sumsPath}`);
	return `url "${base}/${file}"\n      sha256 "${sha}"`;
};

process.stdout.write(`# Generated by scripts/homebrew-formula.ts in mukkund1996/serenity. Do not edit.
class Serenity < Formula
  desc "Mind map of your Claude Code sessions, in the terminal"
  homepage "https://github.com/mukkund1996/serenity"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      ${asset("darwin-arm64")}
    end
    on_intel do
      ${asset("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
      ${asset("linux-arm64")}
    end
    on_intel do
      ${asset("linux-x64")}
    end
  end

  depends_on "gh"
  depends_on "git"
  depends_on "tmux"

  def install
    bin.install Dir["serenity-*"].first => "serenity"
  end

  def caveats
    <<~EOS
      serenity runs your sessions with Claude Code. If you don't have it yet:
        brew install --cask claude-code
      Log in to GitHub for PR status:
        gh auth login
      Then run \`serenity\` inside any git repo.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/serenity version")
  end
end
`);
